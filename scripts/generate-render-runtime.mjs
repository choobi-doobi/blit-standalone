#!/usr/bin/env node
/**
 * Regenerates server/lib/renderRuntime.generated.ts: the Blit engine bundled
 * from server/lib/renderEntry.ts into a source STRING that the render sandbox
 * (server/lib/renderSandbox.ts) runs inside a vm context.
 *
 *   node scripts/generate-render-runtime.mjs          # rewrite the file
 *   node scripts/generate-render-runtime.mjs --check  # exit 1 when it is stale
 *
 * Run it after any change under client/lib/blit/ or to server/lib/renderEntry.ts.
 * `npm test` runs --check.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = path.join(ROOT, 'server/lib/renderEntry.ts');
const OUT = path.join(ROOT, 'server/lib/renderRuntime.generated.ts');

const result = await build({
  entryPoints: [ENTRY],
  bundle: true,
  platform: 'browser',
  format: 'iife',
  globalName: 'BlitRender',
  target: 'es2022',
  minify: true,
  write: false,
  absWorkingDir: ROOT,
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'none',
  logLevel: 'warning',
});
const source = result.outputFiles[0].text;

const text = [
  '// Generated by scripts/generate-render-runtime.mjs from server/lib/renderEntry.ts.',
  '// Do not edit by hand: rerun the script after any change under client/lib/blit/',
  '// or to server/lib/renderEntry.ts. npm test checks it is current.',
  '',
  '/** The engine as a script defining `BlitRender.render`. See server/lib/renderSandbox.ts. */',
  `export const RENDER_RUNTIME_SOURCE = ${JSON.stringify(source)};`,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  let current = null;
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    current = null;
  }
  if (current !== text) {
    console.error('server/lib/renderRuntime.generated.ts is stale: run npm run runtime');
    process.exit(1);
  }
  console.log(`server/lib/renderRuntime.generated.ts is current (${source.length} bytes)`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote server/lib/renderRuntime.generated.ts (${source.length} bytes)`);
}
